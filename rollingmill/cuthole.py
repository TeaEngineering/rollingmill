#!/usr/bin/env python3
"""Cut a round through-hole in thin sheet, leaving four break-off tabs.

Generates MDX-40A g-code that mills a circular hole of a given outer
diameter (OD) with a flat end mill, centred on the workspace origin. The
tool follows the *inside* of the hole, so the cutter-centre path radius is
``OD/2 - tool_dia/2`` and the finished hole diameter equals ``OD``.

The cut ramps down in flat passes of ``--z-step`` mm until it breaks
through the material (plus a small ``--overcut`` into the backing). With
``--helix`` the tool instead descends continuously along the arcs (one
``--z-step`` of pitch per revolution) and finishes with one flat pass at
full depth.
``--tabs`` evenly spaced tabs (default 4, at N/S/E/W) are left at full
thickness -- the tool lifts clear over each tab on every pass -- so the
disc stays captive until you finish the tabs with a scalpel/craft knife.
Each tab's width is ``--tab-frac`` of the OD (default 5%).

Emitted as G02/G03-style arcs (I/J centre offsets) suitable for streaming
to the MDX-40A via `rollingmill --file <out.gcode>`, matching the style of
``rollingmill.spiral``.
"""
from __future__ import annotations

import argparse
import math
import sys
from dataclasses import dataclass
from pathlib import Path

from rollingmill import tools as _tools
from rollingmill.tools import resolve as _resolve


@dataclass
class HoleOpts:
    od_mm: float                 # finished hole outer diameter
    tool_dia_mm: float = 5.0     # end-mill diameter
    thickness_mm: float = 1.5    # material thickness (cut through this)
    overcut_mm: float = 0.1      # extra depth past the backing to sever cleanly
    z_step_mm: float = 0.1       # depth of cut per pass / helix pitch per rev
    helix: bool = False          # ramp Z continuously along arcs vs flat steps
    n_tabs: int = 4              # number of evenly spaced break-off tabs
    tab_frac: float = 0.05       # tab width as a fraction of the OD
    x0: float = 0.0              # hole centre X (workspace origin)
    y0: float = 0.0              # hole centre Y (workspace origin)
    feed: float = 200.0
    plunge_feed: float = 50.0
    z_safe: float = 2.0
    return_home: bool = False
    workspace: str | None = None  # e.g. "G54".."G59"; emitted in header if set
    spindle_rpm: int = 10000


def _fmt(v: float) -> str:
    """Format a number with up to 3 decimal places, trimmed."""
    s = f"{v:.3f}"
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def _fmtp(v: float) -> str:
    """Format a position value: up to 3 decimal places, always at least 1."""
    s = f"{v:.3f}"
    if "." in s:
        s = s.rstrip("0")
        if s.endswith("."):
            s += "0"
    if s == "-0.0":
        s = "0.0"
    return s


def _point(cx: float, cy: float, r: float, ang: float) -> tuple[float, float]:
    return (cx + r * math.cos(ang), cy + r * math.sin(ang))


def emit_gcode(opts: HoleOpts) -> str:
    """Render the tabbed hole-cutting program as MDX-40A g-code."""
    if opts.od_mm <= 0:
        raise ValueError(f"od_mm={opts.od_mm} must be positive")
    if opts.tool_dia_mm <= 0:
        raise ValueError(f"tool_dia_mm={opts.tool_dia_mm} must be positive")
    if opts.od_mm <= opts.tool_dia_mm:
        raise ValueError(
            f"od_mm={opts.od_mm} must exceed tool_dia_mm={opts.tool_dia_mm}"
        )
    if opts.thickness_mm <= 0:
        raise ValueError(f"thickness_mm={opts.thickness_mm} must be positive")
    if opts.z_step_mm <= 0:
        raise ValueError(f"z_step_mm={opts.z_step_mm} must be positive")
    if opts.n_tabs < 1:
        raise ValueError(f"n_tabs={opts.n_tabs} must be >= 1")
    if not (0.0 <= opts.tab_frac < 0.5):
        raise ValueError(f"tab_frac={opts.tab_frac} must be in [0, 0.5)")

    cx, cy = opts.x0, opts.y0
    path_r = (opts.od_mm - opts.tool_dia_mm) / 2.0  # cutter-centre radius

    # The circle is split into n_tabs equal segments; each segment is cut
    # bar a gap at its start, leaving a full-thickness tab there. Gaps are
    # centred at k * seg starting from 0 deg (E) -- so n_tabs=4 lands on
    # E/N/W/S. Tab angular width is the tab arc length (tab_frac * OD)
    # mapped onto the cutter-centre circle.
    seg = 2.0 * math.pi / opts.n_tabs
    tab_len = opts.tab_frac * opts.od_mm
    tab_ang = tab_len / path_r
    if tab_ang >= seg:
        raise ValueError(
            f"tabs too wide: tab arc {_fmt(tab_len)} mm spans "
            f"{_fmt(math.degrees(tab_ang))} deg on the r={_fmt(path_r)} mm "
            f"path, but {opts.n_tabs} tabs leave only {_fmt(math.degrees(seg))} "
            "deg per segment"
        )
    half_tab = tab_ang / 2.0

    total_depth = opts.thickness_mm + opts.overcut_mm
    n_pass = max(1, math.ceil(total_depth / opts.z_step_mm))

    out: list[str] = []
    w = out.append

    w("(Generated by rollingmill.cuthole -- tabbed through-hole)")
    w(f"(OD: {_fmt(opts.od_mm)} mm, tool dia: {_fmt(opts.tool_dia_mm)} mm, "
      f"path radius: {_fmt(path_r)} mm)")
    w(f"(Centre: X{_fmt(cx)} Y{_fmt(cy)}, thickness: {_fmt(opts.thickness_mm)} mm, "
      f"overcut: {_fmt(opts.overcut_mm)} mm)")
    if opts.helix:
        w(f"(Helix: {n_pass} revs x {_fmt(opts.z_step_mm)} mm pitch to "
          f"Z{_fmt(-total_depth)}, plus a flat finishing pass)")
    else:
        w(f"(Passes: {n_pass} x {_fmt(opts.z_step_mm)} mm to Z{_fmt(-total_depth)})")
    w(f"(Tabs: {opts.n_tabs} evenly spaced, {_fmt(tab_len)} mm wide "
      f"= {_fmt(opts.tab_frac * 100)}% of OD, left full thickness)")
    w("%")
    w("O00000001")
    w("G21")  # mm
    w("G90")  # absolute
    w("G17")  # XY plane
    if opts.workspace:
        w(opts.workspace)
    w(f"F{_fmtp(opts.feed)}")
    w(f"S{opts.spindle_rpm}")
    w("M03")  # spindle on (CW)
    w(f"G00 Z{_fmtp(opts.z_safe)}")

    # One cut arc (CCW) per segment, each stopping short of the gap at its
    # start so a full-thickness tab remains between it and the previous arc.
    segments = [
        (k * seg + half_tab, (k + 1) * seg - half_tab)
        for k in range(opts.n_tabs)
    ]

    def flat_pass(z: float, label: str) -> None:
        w(label)
        for a0, a1 in segments:
            sx, sy = _point(cx, cy, path_r, a0)
            ex, ey = _point(cx, cy, path_r, a1)
            w(f"G00 X{_fmtp(sx)} Y{_fmtp(sy)}")
            w(f"G01 Z{_fmtp(z)} F{_fmtp(opts.plunge_feed)}")
            w(f"F{_fmtp(opts.feed)}")
            # CCW arc; centre offset from the arc start point.
            w(f"G03 X{_fmtp(ex)} Y{_fmtp(ey)} "
              f"I{_fmtp(cx - sx)} J{_fmtp(cy - sy)}")
            w(f"G00 Z{_fmtp(opts.z_safe)}")  # lift clear of the tab

    if opts.helix:
        # Continuous helical descent: Z is a linear function of the angle
        # travelled, one z_step per full revolution. The tool still lifts
        # over each tab; the helix resumes deeper on the far side, so the
        # pitch stays constant and a full-height bridge remains at each tab.
        two_pi = 2.0 * math.pi

        def depth(theta: float) -> float:
            return -min(opts.z_step_mm * theta / two_pi, total_depth)

        for rev in range(n_pass):
            w(f"(rev {rev + 1}/{n_pass})")
            for a0, a1 in segments:
                z0 = depth(rev * two_pi + a0)
                z1 = depth(rev * two_pi + a1)
                sx, sy = _point(cx, cy, path_r, a0)
                ex, ey = _point(cx, cy, path_r, a1)
                w(f"G00 X{_fmtp(sx)} Y{_fmtp(sy)}")
                w(f"G01 Z{_fmtp(z0)} F{_fmtp(opts.plunge_feed)}")
                w(f"F{_fmtp(opts.feed)}")
                # Helical CCW arc: XY arc with a simultaneous linear Z ramp.
                w(f"G03 X{_fmtp(ex)} Y{_fmtp(ey)} Z{_fmtp(z1)} "
                  f"I{_fmtp(cx - sx)} J{_fmtp(cy - sy)}")
                w(f"G00 Z{_fmtp(opts.z_safe)}")  # lift clear of the tab
        # Level the ramped floor and guarantee full depth everywhere.
        flat_pass(-total_depth, "(finishing pass at full depth)")
    else:
        for i in range(1, n_pass + 1):
            z = -min(i * opts.z_step_mm, total_depth)
            flat_pass(z, f"(pass {i}/{n_pass}, Z{_fmt(z)})")

    if opts.return_home:
        w("G00 X0.0 Y0.0")
    w("M05")
    w("M30")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--od", type=float, required=True,
                   help="Finished hole outer diameter in mm")
    p.add_argument("--out", type=Path, required=True,
                   help="Output .gcode file path")
    p.add_argument("--tool-dia", type=float, default=None,
                   help="End-mill diameter mm (default 5.0, or from --tool)")
    p.add_argument("--thickness", type=float, default=1.5,
                   help="Material thickness mm to cut through (default 1.5)")
    p.add_argument("--overcut", type=float, default=0.1,
                   help="Extra depth past the backing mm (default 0.1)")
    p.add_argument("--z-step", type=float, default=0.1,
                   help="Depth of cut per pass mm, or helix pitch per "
                        "revolution with --helix (default 0.1)")
    p.add_argument("--helix", action="store_true",
                   help="Ramp Z continuously down the arcs (helical), one "
                        "--z-step per revolution, instead of flat stepped "
                        "passes; adds a flat finishing pass at full depth")
    p.add_argument("--tabs", type=int, default=4,
                   help="Number of evenly spaced break-off tabs (default 4)")
    p.add_argument("--tab-frac", type=float, default=0.05,
                   help="Tab width as a fraction of OD (default 0.05 = 5%%)")
    p.add_argument("--x0", type=float, default=0.0,
                   help="Hole centre X in mm (default 0.0)")
    p.add_argument("--y0", type=float, default=0.0,
                   help="Hole centre Y in mm (default 0.0)")
    p.add_argument("--feed", type=float, default=None,
                   help="Cutting feed mm/min (default 200, or from --tool)")
    p.add_argument("--plunge-feed", type=float, default=None,
                   help="Z plunge feed mm/min (default 50, or from --tool)")
    p.add_argument("--z-safe", type=float, default=2.0,
                   help="Retract Z height mm (default 2.0)")
    p.add_argument("--return-home", action="store_true",
                   help="Append G00 X0 Y0 at end of program")
    p.add_argument("--workspace", default=None,
                   choices=["G54", "G55", "G56", "G57", "G58", "G59"],
                   help="Workspace offset to select in header (e.g. G54)")
    p.add_argument("--spindle-rpm", type=int, default=None,
                   help="Spindle speed in RPM, emitted with M03 "
                        "(default 10000, or from --tool)")
    p.add_argument("--tool", default=None,
                   help="Tool id or name from ~/.rollingmill/tools.json; "
                        "supplies defaults for --tool-dia, --feed, "
                        "--plunge-feed and --spindle-rpm if those are not set")
    args = p.parse_args(argv)

    if args.od <= 0:
        p.error(f"--od ({args.od}) must be positive")

    tool = None
    if args.tool is not None:
        try:
            tool = _tools.find(_tools.load(), args.tool)
        except (KeyError, ValueError) as e:
            p.error(str(e))

    opts = HoleOpts(
        od_mm=args.od,
        tool_dia_mm=_resolve(args.tool_dia, tool, "diameter_mm", 5.0),
        thickness_mm=args.thickness,
        overcut_mm=args.overcut,
        z_step_mm=args.z_step,
        helix=args.helix,
        n_tabs=args.tabs,
        tab_frac=args.tab_frac,
        x0=args.x0, y0=args.y0,
        feed=_resolve(args.feed, tool, "feed_mm_min", 200.0),
        plunge_feed=_resolve(args.plunge_feed, tool, "plunge_feed_mm_min", 50.0),
        z_safe=args.z_safe,
        return_home=args.return_home,
        workspace=args.workspace,
        spindle_rpm=_resolve(args.spindle_rpm, tool, "spindle_rpm", 10000),
    )
    try:
        gcode = emit_gcode(opts)
    except ValueError as e:
        p.error(str(e))
    args.out.write_text(gcode)
    print(f"wrote {args.out} ({len(gcode.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
