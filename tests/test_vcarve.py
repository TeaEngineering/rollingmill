def test_butt_cap_trims_groove_and_adds_end_spurs():
    from rollingmill.vcarve import StrokeSpec
    line = [(10.0, 25.0), (90.0, 25.0)]  # 80 mm long, width 2 -> r=1
    spec = StrokeSpec(subpaths=[line], width_mm=2.0, linecap="butt")
    opts = VCarveOpts(page_w_mm=100, page_h_mm=50, half_angle_deg=30, max_depth_mm=10)
    tps = vcarve._stroke_toolpaths(spec, opts)
    # groove is trimmed by r at each end: spans ~11..89 in X
    groove = max(tps, key=lambda t: len(t.pts))
    xs = [p[0] for p in groove.pts]
    assert min(xs) == pytest.approx(11.0, abs=1e-6) and max(xs) == pytest.approx(89.0, abs=1e-6)
    # four cap spurs (two per end), each ramping to the surface
    caps = [t for t in tps if len(t.pts) == 2 and min(p[2] for p in t.pts) <= 1e-9]
    assert len(caps) == 4


