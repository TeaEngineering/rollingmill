"""Tests for rollingmill.vcarve.

Geometry is exercised with synthetic masks so Inkscape is not required. The
heavy deps (numpy/scipy/scikit-image/pillow) are optional, so skip cleanly
when they are absent.
"""

import math

import pytest

np = pytest.importorskip("numpy")
pytest.importorskip("skimage")
pytest.importorskip("scipy")
pytest.importorskip("PIL")

from rollingmill import vcarve  # noqa: E402
from rollingmill.vcarve import ToolPath, VCarveOpts  # noqa: E402

_HALF = math.tan(math.radians(30))


def _write_svg(tmp_path, body, w=100, h=50):
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{w}mm" height="{h}mm" viewBox="0 0 {w} {h}">{body}</svg>'
    )
    p = tmp_path / "in.svg"
    p.write_text(svg)
    return p


def _bar_mask(h=100, w=200, top=40, bot=60, left=10, right=190):
    """A filled horizontal bar; thickness = bot-top pixels."""
    m = np.zeros((h, w), dtype=bool)
    m[top:bot, left:right] = True
    return m


def test_depth_from_clearance_matches_bit_geometry():
    opts = VCarveOpts(half_angle_deg=30.0, max_depth_mm=100.0)
    # r = d * tan(t)  =>  d = r / tan(t)
    assert vcarve._depth_from_clearance(5.0, opts) == pytest.approx(5.0 / math.tan(math.radians(30)))
    # clamps to max_depth
    opts2 = VCarveOpts(half_angle_deg=30.0, max_depth_mm=2.0)
    assert vcarve._depth_from_clearance(5.0, opts2) == pytest.approx(2.0)


def test_bar_medial_axis_depth_follows_width():
    # 20 px thick bar at 0.5 mm/px -> 10 mm wide -> half-width 5 mm.
    opts = VCarveOpts(page_w_mm=100.0, page_h_mm=50.0, pitch_mm=0.5,
                      half_angle_deg=30.0, max_depth_mm=100.0, prune_mm=0.0,
                      chord_tol_mm=0.01, min_depth_mm=0.0)
    paths = vcarve.build_toolpaths(_bar_mask(), opts)
    assert paths, "expected at least one toolpath"
    got = max(p.max_depth for p in paths)
    expected = 5.0 / math.tan(math.radians(30))  # ~8.66 mm
    assert got == pytest.approx(expected, abs=0.4)


def test_y_axis_is_flipped_to_bed_coordinates():
    # Bar near the TOP of the page (rows 10..20 -> svg-y ~7.5 mm). On a 50 mm
    # page the flipped bed-y must land near the FAR edge (~42.5 mm), not ~7.5.
    opts = VCarveOpts(page_w_mm=100.0, page_h_mm=50.0, pitch_mm=0.5, prune_mm=0.0)
    paths = vcarve.build_toolpaths(_bar_mask(top=10, bot=20), opts)
    ys = [y for p in paths for (_x, y, _z) in p.pts]
    assert ys and all(y > 40.0 for y in ys)  # flipped to the far edge


def test_min_depth_floors_faint_thin_lines():
    m = np.zeros((60, 200), dtype=bool)
    m[29:31, 10:190] = True  # 2 px (1 mm) thin line -> natural depth ~0.87 mm
    opts = VCarveOpts(page_w_mm=100.0, page_h_mm=30.0, pitch_mm=0.5,
                      min_depth_mm=1.5, prune_mm=0.0, max_depth_mm=100.0)
    paths = vcarve.build_toolpaths(m, opts)
    assert paths
    depths = [z for p in paths for (_x, _y, z) in p.pts]
    # whole faint branch promoted to the floor (1.5 > natural 0.87)
    assert min(depths) == pytest.approx(1.5, abs=1e-6)
    assert max(depths) == pytest.approx(1.5, abs=1e-6)


def test_passes_split_by_stepdown():
    path = ToolPath([(0.0, 0.0, 3.0), (10.0, 0.0, 3.0)])
    opts = VCarveOpts(stepdown_mm=0.6)
    passes = [seq for seq, _arcs in vcarve._passes_for(path, opts)]
    assert len(passes) == 5  # ceil(3.0 / 0.6)
    deepest = min(z for seg in passes for (_x, _y, z) in seg)
    assert deepest == pytest.approx(-3.0)
    # First pass floors at -0.6, alternate passes reverse direction.
    assert min(z for _x, _y, z in passes[0]) == pytest.approx(-0.6)
    assert passes[1][0][0] == pytest.approx(path.pts[-1][0])  # reversed start


def test_emit_gcode_has_wellformed_header_and_footer():
    path = ToolPath([(10.0, 10.0, 1.0), (20.0, 10.0, 1.5), (30.0, 10.0, 0.2)])
    opts = VCarveOpts(spindle_rpm=14000, feed=400.0, plunge_feed=80.0, workspace="G54")
    g = vcarve.emit_gcode([path], opts)
    lines = g.splitlines()
    assert lines[0].startswith("(Generated by rollingmill.vcarve")
    for token in ("%", "G21", "G90", "G17", "G54", "S14000", "M03", "M05", "M30"):
        assert any(line == token or line.startswith(token) for line in lines), token
    # cutting moves never go above the surface (Z <= 0 on G01), spindle stops last
    assert lines[-1] == "M30"
    assert "M05" in lines


def test_stroke_only_svg_needs_no_inkscape_and_uses_declared_width(tmp_path):
    pytest.importorskip("svgelements")
    # A 2 mm stroke -> constant depth = (2/2)/tan(30) = 1.732 mm, everywhere.
    svg = _write_svg(tmp_path, '<path d="M 10,25 L 90,25" '
                     'style="fill:none;stroke:#000;stroke-width:2"/>')
    opts = VCarveOpts(page_w_mm=100, page_h_mm=50, half_angle_deg=30,
                      max_depth_mm=10, markers=False)
    ids, strokes, has_fill = vcarve.parse_svg_features(svg, opts)
    assert not has_fill and len(strokes) == 1
    assert strokes[0].width_mm == pytest.approx(2.0, abs=1e-3)
    # run() must not touch Inkscape when there are no fills.
    g = vcarve.run(svg, opts, is_png=False)
    zs = [float(tok[1:]) for line in g.splitlines() if line.startswith("G01")
          for tok in line.split() if tok.startswith("Z")]
    assert min(zs) == pytest.approx(-1.0 / _HALF, abs=1e-3)  # deepest = 1.732
    # Y is flipped: svg y=25 on a 50 mm page -> bed y=25.
    ys = [float(tok[1:]) for line in g.splitlines() if line.startswith(("G00", "G01"))
          for tok in line.split() if tok.startswith("Y")]
    assert ys and all(24.0 <= y <= 26.0 for y in ys)


def test_crossing_strokes_do_not_deepen_at_the_intersection(tmp_path):
    pytest.importorskip("svgelements")
    # Two 2 mm strokes forming an X. Medial-axis rasterising would dive at the
    # crossing; vector handling keeps every point at the constant stroke depth.
    body = ('<path d="M 10,10 L 90,90" style="fill:none;stroke:#000;stroke-width:2"/>'
            '<path d="M 10,90 L 90,10" style="fill:none;stroke:#000;stroke-width:2"/>')
    svg = _write_svg(tmp_path, body, w=100, h=100)
    opts = VCarveOpts(page_w_mm=100, page_h_mm=100, half_angle_deg=30,
                      max_depth_mm=10, markers=False)
    g = vcarve.run(svg, opts, is_png=False)
    zs = [float(tok[1:]) for line in g.splitlines() if line.startswith("G01")
          for tok in line.split() if tok.startswith("Z")]
    assert min(zs) == pytest.approx(-1.0 / _HALF, abs=1e-3)  # no deeper than 1.732


