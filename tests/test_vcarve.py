def test_png_roundtrip_mask(tmp_path):
    from PIL import Image

    arr = np.full((20, 30), 255, dtype=np.uint8)
    arr[5:15, 8:22] = 0  # black block
    png = tmp_path / "m.png"
    Image.fromarray(arr, mode="L").save(png)
    mask = vcarve.load_png_to_mask(png, threshold=200)
    assert mask.dtype == bool
    assert mask[10, 15] and not mask[0, 0]
