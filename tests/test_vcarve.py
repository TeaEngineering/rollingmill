def test_miter_join_spur_points_to_the_outer_corner():
    from rollingmill.vcarve import StrokeSpec
    # 90 deg corner: up then right. Outer (convex) side is upper-left.
    sp = [(0.0, -10.0), (0.0, 0.0), (10.0, 0.0)]
    spec = StrokeSpec(subpaths=[sp], width_mm=2.0)  # r=1, miter tip = V + r*(-1, 1)
    spurs = vcarve._join_spurs(sp, 1, closed=False, r=1.0, depth=2.0, spec=spec)
    assert len(spurs) == 1
    base, tip = spurs[0]
    assert base[:2] == (0.0, 0.0) and base[2] == pytest.approx(2.0)  # full depth at vertex
    assert tip[0] == pytest.approx(-1.0, abs=1e-6) and tip[1] == pytest.approx(1.0, abs=1e-6)
    assert tip[2] == pytest.approx(0.0)  # ramps to the surface at the point


def test_miterlimit_falls_back_to_bevel_two_spurs():
    from rollingmill.vcarve import StrokeSpec
    # A near-hairpin (~168 deg turn): 1/sin(theta/2) huge -> exceeds miterlimit 4.
    sp = [(0.0, 0.0), (10.0, 0.0), (0.2, 1.0)]
    spec = StrokeSpec(subpaths=[sp], width_mm=2.0, miterlimit=4.0)
    spurs = vcarve._join_spurs(sp, 1, closed=False, r=1.0, depth=2.0, spec=spec)
    assert len(spurs) == 2  # bevel: one spur to each shoulder
    # explicit bevel request also yields two
    spec2 = StrokeSpec(subpaths=[sp], width_mm=2.0, linejoin="bevel")
    assert len(vcarve._join_spurs(sp, 1, False, 1.0, 2.0, spec2)) == 2


