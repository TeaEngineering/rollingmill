def test_circular_stroke_becomes_one_arc_and_emits_g02_g03():
    from rollingmill.vcarve import StrokeSpec
    # a semicircle radius 20 about (50,50); round cap so no cap spurs/trim
    sub = [(50 + 20 * math.cos(t), 50 - 20 * math.sin(t)) for t in
           [i / 40 * math.pi for i in range(41)]]
    opts = VCarveOpts(page_w_mm=100, page_h_mm=100, half_angle_deg=30,
                      max_depth_mm=10, markers=False, arcs=True)
    spec = StrokeSpec(subpaths=[sub], width_mm=2.0, linecap="round")
    tps = vcarve._stroke_toolpaths(spec, opts)
    main = max(tps, key=lambda t: len(t.pts))
    assert len(main.arcs) == 1 and len(main.pts) == 3  # whole semicircle -> one arc
    # reconstruct the arc centre from the emitted I/J and check radius
    cx, cy, cw = main.arcs[0]
    p0 = main.pts[0]
    assert math.hypot(p0[0] - cx, p0[1] - cy) == pytest.approx(20.0, abs=0.05)
    g = vcarve.emit_gcode(tps, opts)
    assert "G02" in g or "G03" in g
    assert "I" in g and "J" in g


